'''
【程序42】
题目：809*??=800*??+9*??+1   其中??代表的两位数,8*??的结果为两位数，9*??的结果为3位数。求??代表的两位数，及809*??后的结果。
'''

for x in range(10, 100):
    if 8 * x < 100 and 9 * x >= 100:
        if 809 * x == 800 * x + 9 * x + 1:
            print("??代表的两位数是:", x)
            print("809*??的结果是:", 809 * x)
            break
else:
    print("没有找到满足条件的两位数")